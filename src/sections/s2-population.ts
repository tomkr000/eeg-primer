import { netDipole, mulberry32 } from '../physics/population';
import { solveShells, surfacePotential } from '../physics/sphere';
import { controls, readout, slider, fmt } from '../ui/slider';
import { linePlot, type Series } from '../ui/plot';
import { P, claimCite as c, defaultHead } from '../data/params';
import { section, figure, prose } from '../ui/layout';

export function mountPopulation(root: HTMLElement) {
  const sec = section(root, 'population', '2', 'Strength in numbers — but only in step');
  prose(sec.text, `
<p>Because the quasi-static field is linear, the potentials of many neurons simply add
${c('superposition')}. What matters is <em>how</em> they add. If the synaptic currents of N cells rise and
fall together, their dipole moments add in phase and the far field grows as N. If their timing is
unrelated, the variances add rather than the amplitudes, so the sum grows only as √N and the
population is “loud” only in the sense that a crowd is loud — without a melody
${c('variances-add')}. Synchrony, not head count, is the first requirement for a signal that leaves the
head.</p>
<p>Geometry is the second. Pyramidal cells have long apical dendrites that run parallel to one another,
perpendicular to the cortical surface, so their individual dipoles point the same way and form an
<em>open field</em> that survives at a distance. Cells whose dendrites radiate in all directions
(stellate cells, most interneurons) form <em>closed fields</em> whose currents cancel just outside the cell
${c('open-closed')}. Postsynaptic currents last tens of milliseconds and overlap across cells; action
potentials are a millisecond long and rarely coincide, so the field seen from afar is dominated by
synaptic currents ${c('psp-dominate')}.</p>
<p>Put numbers on it. A single postsynaptic potential is a dipole of about 20 fA·m, so a million
simultaneously active synapses are needed for a typical evoked response ${c('psp-moment')}. A single
layer-5 pyramidal cell produces an equivalent dipole of roughly
${P.singleCellMomentRange[0]}–${P.singleCellMomentRange[1]} pA·m during a synaptic response
${c('single-cell-moment')}; a magnetoencephalography (MEG) or EEG source that is routinely measured is about
10 nA·m, which needs on the order of ${fmt(P.cellsFor10nAm[0], 2)}–${fmt(P.cellsFor10nAm[1], 2)} synchronous
cells ${c('cells-for-10nam')}. Cortex holds about ${fmt(P.neuronsPerMm2, 3)} neurons under each square
millimetre ${c('neuron-density')}, so fifty thousand cells fit under a patch far smaller than a
grain of rice — but they must fire together. In practice, scalp visibility is an areal requirement:
interictal spikes generated by less than 6 cm² of cortex were never seen on the scalp, while those
involving more than 10 cm² were seen about 90% of the time ${c('tao-area')} — the textbook rule of thumb
is 6–10 cm² or more of synchronous cortex ${c('area-rule')}.</p>
<h3>Do supporting cells help?</h3>
<p>Glia outnumber neurons but do not amplify EEG-band signals. Glial membranes do carry current —
astrocytes buffer extracellular potassium and are depolarised by it — but the glial syncytium is thought
to contribute mainly to slow and infra-slow (below ~0.1 Hz) potential shifts, not to rhythms in the
1–100 Hz band ${c('glia-slow')}, and glia are not organised into open fields. What <em>does</em> enlarge
the source are things that increase coherent current per cell or the coherent cell count: dendritic
calcium spikes are large and long-lasting, and in single-cell models the brief action potential itself can
carry up to ~3 pA·m, several times the slow synaptic envelope ${c('ca-spike-moment')}; rhythmic drive
(alpha, beta, gamma oscillations) synchronises large populations ${c('oscillations-synchrony')};
inhibitory synapses contribute currents of their own in actively spiking neurons ${c('inhibitory-contrib')};
and, unlike
magnetoencephalography (MEG), which is nearly blind to radial sources, EEG sees sources of every
orientation with only modest differences in sensitivity (a median ratio of 0.63 between a location’s
least and most visible orientation), so a folded cortex does not hide much from it ${c('orientation')}. None of these changes the basic law: only coherent, aligned current
counts.</p>`);

  const sN = slider({ label: 'Neurons in the active patch, N', min: 1, max: 1e8, value: 1e4, log: true, format: (v) => fmt(v, 2) });
  const sF = slider({ label: 'Fraction firing in synchrony', min: 0, max: 1, step: 0.01, value: 0.1 });
  const sA = slider({ label: 'Alignment of dendrites (mean cosine)', min: 0, max: 1, step: 0.01, value: 0.9, note: c('open-closed') });
  const sP = slider({ label: 'Dipole moment per cell', unit: 'pA·m', min: 0.05, max: 3, value: P.singleCellMomentPAm, log: true, note: c('single-cell-moment') });
  const rMoment = readout('Net dipole moment of the patch');
  const rArea = readout('Cortical area holding N pyramidal cells', c('neuron-density') + c('pyramidal-fraction'));
  const rScalp = readout('Peak scalp potential from this dipole', `(section 3 head model, source 2 mm below the cortex)`);

  const fig = figure(sec.fig, 'Net dipole moment of a population versus its size, for coherent (slope 1), incoherent (slope ½) and mixed summation. Dashed line: a 10 nA·m source, the scale of a routinely measured evoked response.');
  const plot = linePlot(fig.plotArea, {
    x: { label: 'Number of neurons N', scale: 'log', domain: [1, 1e8] },
    y: { label: 'Net dipole moment (nA·m)', scale: 'log', domain: [1e-4, 1e3] },
    height: 320,
  });
  // phasor illustration
  const canvas = document.createElement('canvas');
  canvas.width = 360; canvas.height = 200; canvas.className = 'phasors';
  const pcap = document.createElement('div');
  pcap.className = 'map-caption';
  pcap.textContent = '60 cells as phasors laid head to tail: synchronous cells (blue) point together, the rest (grey) wander. The resultant is the orange arrow.';
  fig.plotArea.append(canvas, pcap);
  fig.controls.append(controls(sN.el, sF.el, sA.el, sP.el), rMoment.el, rArea.el, rScalp.el);

  const head = defaultHead();
  const sol = solveShells(head.shells, head.sourceRadius, 1, 'radial', 120);
  const scalpPerAm = surfacePotential(sol, 0); // V per A·m

  function drawPhasors(f: number) {
    const ctx = canvas.getContext('2d')!;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    const rng = mulberry32(7);
    const n = 60, len = 12;
    let x = 20, y = canvas.height / 2;
    const x0 = x, y0 = y;
    ctx.lineWidth = 2;
    for (let i = 0; i < n; i++) {
      const sync = rng() < f;
      const ang = sync ? 0 : rng() * 2 * Math.PI;
      const nx = x + len * Math.cos(ang), ny = y + len * Math.sin(ang);
      ctx.strokeStyle = sync ? '#2a78d6' : '#b5b3ab';
      ctx.beginPath(); ctx.moveTo(x, y); ctx.lineTo(nx, ny); ctx.stroke();
      x = nx; y = ny;
    }
    ctx.strokeStyle = '#eb6834'; ctx.lineWidth = 3;
    ctx.beginPath(); ctx.moveTo(x0, y0); ctx.lineTo(x, y); ctx.stroke();
    ctx.fillStyle = '#eb6834';
    ctx.beginPath(); ctx.arc(x, y, 4, 0, 2 * Math.PI); ctx.fill();
  }

  function update() {
    const N = sN.value, f = sF.value, a = sA.value, p = sP.value * 1e-12;
    const coh: [number, number][] = [], inc: [number, number][] = [], mix: [number, number][] = [];
    for (let k = 0; k <= 160; k++) {
      const n = Math.pow(10, (8 * k) / 160);
      coh.push([n, netDipole(n, 1, 1, p).total * 1e9]);
      inc.push([n, netDipole(n, 0, 1, p).total * 1e9]);
      mix.push([n, netDipole(n, f, a, p).total * 1e9]);
    }
    const series: Series[] = [
      { name: 'All synchronous & aligned', points: coh, color: '#898781', dashed: true, width: 1.5 },
      { name: 'None synchronous (√N)', points: inc, color: '#898781', dashed: true, width: 1.5 },
      { name: 'Your settings', points: mix, color: '#2a78d6', width: 2.5 },
      { name: 'Current N', points: [[N, netDipole(N, f, a, p).total * 1e9]], color: '#eb6834', dots: true },
    ];
    plot.update(series, [{ axis: 'y', value: 10, label: '10 nA·m: a routinely measured source' }]);
    const m = netDipole(N, f, a, p).total;
    rMoment.set(`${fmt(m * 1e9, 3)} nA·m`);
    const areaMm2 = N / (P.neuronsPerMm2 * P.pyramidalFraction);
    rArea.set(areaMm2 < 100 ? `${fmt(areaMm2, 3)} mm²` : `${fmt(areaMm2 / 100, 3)} cm²`);
    rScalp.set(`${fmt(m * scalpPerAm * 1e6, 3)} µV`);
    drawPhasors(f);
  }
  [sN, sF, sA, sP].forEach((s) => s.onChange(update));
  update();
}
